begin;

-- ─── Colonnes manquantes ────────────────────────────────────────────────────
alter table public.profils
  add column if not exists telephone text,
  add column if not exists adresse text,
  add column if not exists code_postal text,
  add column if not exists ville text,
  add column if not exists photo_profil text;

alter table public.chiens
  add column if not exists numero_de_tatouage varchar;

alter table public.evenements
  add column if not exists heure_debut time,
  add column if not exists heure_fin time,
  add column if not exists id_profil uuid references public.profils (id) on delete set null,
  add column if not exists id_google text;

alter table public.publication
  add column if not exists id_profil uuid references public.profils (id) on delete set null;

-- participation.id_profil était un entier : c'est l'identifiant (uuid) du profil
do $$
begin
  if (select data_type from information_schema.columns
      where table_schema = 'public' and table_name = 'participation' and column_name = 'id_profil') = 'bigint' then
    if exists (select 1 from public.participation where id_profil is not null) then
      raise exception 'participation contient des id_profil entiers : conversion manuelle nécessaire';
    end if;
    alter table public.participation alter column id_profil type uuid using null;
    alter table public.participation
      add constraint participation_id_profil_fkey foreign key (id_profil) references public.profils (id) on delete cascade;
  end if;
end;
$$;

-- ─── Résultats (tables absentes de la sauvegarde) ───────────────────────────
create table if not exists public."categorieResultat" (
  id bigint primary key,
  nom_categorie text not null
);

-- Identifiants attendus par le code (pages Résultats)
insert into public."categorieResultat" (id, nom_categorie) values
  (1, 'Cross'), (2, 'Trail'), (3, 'Marche'), (4, 'VTT'), (5, 'Trottinette')
on conflict (id) do nothing;

create table if not exists public."resultatType" (
  id bigint generated by default as identity primary key,
  nom_resultat text not null unique
);

-- Types de départ, à renommer ou compléter par le bureau
insert into public."resultatType" (nom_resultat) values ('Compétition'), ('Entraînement')
on conflict (nom_resultat) do nothing;

create table if not exists public.resultats (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  id_profil uuid references public.profils (id) on delete cascade,
  id_chien bigint references public.chiens (id) on delete set null,
  id_evenement bigint references public.evenements (id) on delete set null,
  id_type bigint references public."resultatType" (id),
  id_categorie bigint references public."categorieResultat" (id),
  "nomActivite" text,
  lieu text,
  region text,
  distance text,
  temps text,
  "minKm" text,
  vitesse text,
  "kmAR" text,
  classement integer,
  date date
);

-- ─── Droits d'accès à l'API (les nouvelles tables ne sont pas exposées d'office) ─
-- La RLS décide ensuite ligne par ligne : anon ne fait que lire.
grant usage on schema public to anon, authenticated, service_role;
grant select on all tables in schema public to anon;
grant select, insert, update, delete on all tables in schema public to authenticated, service_role;
grant usage, select on all sequences in schema public to authenticated, service_role;
grant execute on all functions in schema public to anon, authenticated, service_role;

commit;
